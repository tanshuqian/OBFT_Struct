# =====================================================================
# 3. 映射匹配执行函数
# =====================================================================
def map_to_categories_advanced(diag_name):
    cleaned_text = clean_diagnosis(diag_name)
    for category, keywords in CATEGORIES_MAPPING.items():
        for keyword in keywords:
            if keyword in cleaned_text:
                return category
    return '11. 无法明确分类(长尾)'


# =====================================================================
# 4. 核心执行、排序与看板打印
# =====================================================================
def run_optimization_analysis(file_path):
    print(f"正在读取数据: {file_path} ...")

    try:
        if str(file_path).endswith('.csv'):
            df_out = pd.read_csv(file_path)
        else:
            df_out = pd.read_excel(file_path, sheet_name="门诊诊断排序")
    except Exception as e:
        print(f"文件读取失败，请检查路径。错误信息: {e}")
        return

    # 规范列名
    df_out.columns = ['排名', '诊断名称', '出现次数', '占比(%)']

    # 应用高级映射字典
    df_out['10大分类'] = df_out['诊断名称'].apply(map_to_categories_advanced)

    # 统计看板数据
    grouped = df_out.groupby('10大分类')['出现次数'].sum().reset_index()
    total_occurrences = grouped['出现次数'].sum()
    grouped['占比(%)'] = (grouped['出现次数'] / total_occurrences * 100).round(2)

    # 提取开头的数字，让数据强制按照 1 到 11 的顺序排列
    grouped['SortIndex'] = grouped['10大分类'].apply(lambda x: int(x.split('.')[0]))
    grouped = grouped.sort_values(by='SortIndex').drop(columns=['SortIndex'])

    print("\n" + "=" * 50)
    print("=== 产科 EMR V11.0 总体分布看板 (完美排序版) ===")
    print("=" * 50)
    print(grouped.to_string(index=False))

    # 盲区分析与覆盖率计算
    unmapped = df_out[df_out['10大分类'] == '11. 无法明确分类(长尾)']
    if not unmapped.empty:
        unmapped_percentage = grouped[grouped['10大分类'] == '11. 无法明确分类(长尾)']['占比(%)'].values[0]
        coverage_rate = 100 - unmapped_percentage

        print("\n" + "=" * 50)
        print(f"=== 当前核心结构覆盖率: {coverage_rate:.2f}% ===")
        print("=== Top 15 未分类长尾诊断 (已过滤废词) ===")
        print("=" * 50)

        unmapped_valid = unmapped[unmapped['诊断名称'] != '其他的']
        if not unmapped_valid.empty:
            print(
                unmapped_valid[['诊断名称', '出现次数']].sort_values(by='出现次数', ascending=False).head(15).to_string(
                    index=False))
        else:
            print("除纯系统废词外，已 100% 覆盖所有有意义的门诊诊断！")
    else:
        print("\n太完美了！当前字典已 100% 覆盖所有门诊诊断样本！")


