# =====================================================================
# 1. 文本预处理与去噪函数
# =====================================================================
def clean_diagnosis(text):
    text = str(text).upper()
    # 剔除所有括号及其内部内容
    text = re.sub(r'[（\(].*?[）\)]', '', text)

    # 剔除高频干扰噪音词（注意：未包含"状态"，避免误杀"妊娠状态"）
    noise_words = [
        '监督', '个人史', '家族史', '的', '未特指', '伴有', '伴',
        '轻度', '中度', '重度', 'Ⅰ度', 'Ⅱ度', 'Ⅲ度', '单活胎', '双活胎', '妊娠合并'
    ]
    for noise in noise_words:
        text = text.replace(noise, '')

    return text.strip()


